"""Write the README's results section from result files only.

    python scripts/update_readme.py            # reads results/, rewrites the marked section of README.md
    python scripts/update_readme.py --check    # validate and print the section, don't write

Everything between the markers is generated from results/env.json, results/bench_kernels.json and
results/<env>/summary.json (written by scripts/run_a100.sh); nothing in it is typed by hand. The
script refuses results that did not come from a CUDA GPU (episodes whose device isn't cuda, a
benchmark that didn't run compiled Triton), so CPU smoke runs can never reach the README.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
BEGIN, END = "<!-- results:begin -->", "<!-- results:end -->"


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def problems(env, bench, summaries):
    out = []
    if not env or env.get("device") != "cuda":
        out.append("env.json is missing or not from a CUDA run")
    if bench and (bench.get("device") != "cuda" or bench.get("kernel_path") != "triton"):
        out.append(f"bench_kernels.json ran on {bench.get('device')} with {bench.get('kernel_path')}, "
                   "not compiled Triton on CUDA")
    for name, s in summaries:
        for c in s["configs"]:
            if c.get("devices") != ["cuda"]:
                out.append(f"{name}/summary.json: '{c['name']}' ran on {c.get('devices')}, not cuda")
    if not bench and not summaries:
        out.append("no results found")
    return out


def ci(x, interval, signed=False):
    if x is None:
        return "n/a"
    v = f"{x:+.3f}" if signed else f"{x:.3f}"
    return v if not interval or interval[0] is None else f"{v} [{interval[0]:.2f}, {interval[1]:.2f}]"


def pct(x):
    return "n/a" if x is None else f"{x:.0%}"


def render(env, bench, summaries, results_dir, readme_dir):
    lines = [BEGIN, "## Results", "",
             f"Generated by `scripts/update_readme.py` from the files in `results/`; do not edit by hand. "
             f"Run on {env['gpu']} (torch {env['torch']}, CUDA {env['cuda']}, triton {env['triton']}, "
             f"transformers {env['transformers']}), commit `{(env.get('git_sha') or '?')[:7]}`, {env['date'][:10]}.", ""]
    for name, s in summaries:
        full = next((c for c in s["configs"] if c["name"] == "FullKV"), None)
        if full and full["acc"] == 0:
            # with no FullKV successes every policy scores 0 too, so the table can't tell them apart
            lines += [f"### {name}", "",
                      f"Not shown: FullKV solved 0 of {full['n_tasks']} tasks, so this run can't tell the eviction "
                      f"policies apart. The raw results are in `results/{name}/`.", ""]
            continue
        cfg = s["configs"][0]["config"]
        lines += [f"### {name}", "",
                  f"Model `{cfg.get('model')}`, thinking {'off' if cfg.get('no_thinking') else 'on'}, "
                  f"up to {cfg.get('max_new_tokens')} new tokens per round. *tasks* and *episodes* are each "
                  f"config's sample size. Accuracy has a 95% bootstrap CI over tasks; Δ is the paired "
                  f"difference from FullKV on the same tasks. Peak KV and trace length are relative to FullKV.", "",
                  "| config | tasks | episodes | accuracy [95% CI] | Δ vs FullKV [95% CI] | peak KV / FullKV | trace / FullKV |",
                  "|---|---:|---:|---:|---:|---:|---:|"]
        for c in s["configs"]:
            lines.append(f"| {c['name']} | {c['n_tasks']} | {c['n_episodes']} | {ci(c['acc'], c['acc_ci'])} | "
                         f"{ci(c['delta_vs_full'], c['delta_ci'], signed=True)} | {pct(c['peak_vs_full'])} | "
                         f"{pct(c['trace_vs_full'])} |")
        png = os.path.join(results_dir, name, "pareto.png")
        if os.path.exists(png):
            lines += ["", f"![{name}: accuracy vs peak KV memory]({os.path.relpath(png, readme_dir)})"]
        lines.append("")
    if bench:
        lines += ["### Kernel benchmark (one compression step)", "",
                  f"{bench['gpu']}, {bench['dtype']}, block {bench['block_size']}, {bench['kv_heads']} KV heads, "
                  f"{bench['q_heads']} query heads, head dim {bench['head_dim']}, {bench['n_layers']} layer; "
                  f"median of {bench['iters']} runs after {bench['warmup']} warm-up. Extra memory is the peak "
                  "allocated during the step, measured with `torch.cuda.max_memory_allocated`.", "",
                  "| tokens → budget | requests | ActKV ms | gather ms | speedup | ActKV extra MB | gather extra MB | same result |",
                  "|---|---:|---:|---:|---:|---:|---:|---|"]
        for r in bench["rows"]:
            same = "yes" if r["masks_match"] and r["outputs_match"] else "**no**"
            lines.append(f"| {r['n']} → {r['budget']} | {r['r']} | {r['actkv_ms']:.3f} | {r['gather_ms']:.3f} | "
                         f"{r['gather_ms'] / r['actkv_ms']:.2f}x | {r['actkv_extra_mb']:.1f} | "
                         f"{r['gather_extra_mb']:.1f} | {same} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--readme", default=os.path.join(ROOT, "README.md"))
    ap.add_argument("--check", action="store_true", help="validate and print, don't write")
    args = ap.parse_args(argv)
    env = load(os.path.join(args.results, "env.json"))
    bench = load(os.path.join(args.results, "bench_kernels.json"))
    summaries = [(d, load(os.path.join(args.results, d, "summary.json"))) for d in sorted(os.listdir(args.results))
                 if os.path.exists(os.path.join(args.results, d, "summary.json"))] if os.path.isdir(args.results) else []
    bad = problems(env, bench, summaries)
    if bad:
        print("refusing to update the README:\n  " + "\n  ".join(bad), file=sys.stderr)
        return 1
    section = render(env, bench, summaries, args.results, os.path.dirname(os.path.abspath(args.readme)))
    if args.check:
        print(section)
        return 0
    with open(args.readme) as f:
        text = f.read()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        print(f"{args.readme} needs exactly one {BEGIN} ... {END} block", file=sys.stderr)
        return 1
    head, rest = text.split(BEGIN)
    with open(args.readme, "w") as f:
        f.write(head + section + rest.split(END, 1)[1])
    print(f"updated {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
